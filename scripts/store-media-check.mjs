import { access, readFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
for (const file of [
  "scripts/store-media-smoke.mjs",
  "scripts/store-assets-smoke.mjs",
  "store/chrome-web-store-v0.2.json",
  "src/assets/icons/browsercrew-16.png",
  "src/assets/icons/browsercrew-32.png",
  "src/assets/icons/browsercrew-48.png",
  "src/assets/icons/browsercrew-128.png",
  ".github/workflows/quality.yml",
  "manifest.json",
  "package.json",
  "docs/CHROME-WEB-STORE-v0.2.md",
  "docs/STORE-MEDIA-v0.2.md",
  "docs/RELEASE-EVIDENCE-v0.2.md"
]) await access(file);

await Promise.all([
  execFileAsync(process.execPath, ["--check", "scripts/store-media-smoke.mjs"]),
  execFileAsync(process.execPath, ["--check", "scripts/store-assets-smoke.mjs"])
]);

const smoke = await readFile("scripts/store-media-smoke.mjs", "utf8");
for (const phrase of [
  'channel: "chromium",',
  'viewport: { width: 1280, height: 800 }',
  'browsercrew-workspace-1280x800.png',
  'await panel.screenshot({ path: screenshotPath, type: "png", fullPage: false })',
  'assert.deepEqual(dimensions, { width: 1280, height: 800 }',
  'kind: "browsercrew.store_media_evidence"',
  'event?.pull_request?.head?.sha || event?.after',
  'Installed extension connected through the progressive Connect AI popup and returned to Chat',
  '#saveConnectionButton',
  '#aiSetupCloseButton',
  'real Workspace compare UI with three user-selected pages'
]) if (!smoke.includes(phrase)) throw new Error(`Store media smoke contract missing: ${phrase}`);

const assetSmoke = await readFile("scripts/store-assets-smoke.mjs", "utf8");
for (const phrase of [
  'id: "icon_128_png"',
  'source: "src/assets/icons/browsercrew-128.png"',
  '7d707768a259207a1a5963c8cf351f297ccef482153f50d14fd05abf0682ce09',
  'paddingPx: 16',
  'width: 96, height: 96',
  '16px transparent padding on every side',
  'browsercrew-small-promo-440x280.png',
  'viewport: { width: 440, height: 280 }',
  'BrowserCrew',
  'Your browser workbench',
  'Choose your AI',
  'Choose the page',
  'Stay in control',
  'await page.screenshot({ path: promoPath, type: "png", fullPage: false })',
  'assert.deepEqual(promoDimensions, { width: 440, height: 280 }',
  'exact_candidate_browsercrew_brand_render',
  'report.media = ['
]) if (!assetSmoke.includes(phrase)) throw new Error(`Reviewed store-asset smoke contract missing: ${phrase}`);

const contract = JSON.parse(await readFile("store/chrome-web-store-v0.2.json", "utf8"));
const screenshot = contract.requiredStoreAssets?.find((asset) => asset.id === "screenshot_1280x800");
if (!screenshot) throw new Error("Store contract must track the required 1280x800 screenshot.");
if (screenshot.status !== "generated_by_ci") throw new Error("The required store screenshot must remain generated_by_ci.");
if (screenshot.path !== "artifacts/store-media/browsercrew-workspace-1280x800.png") throw new Error("Store screenshot contract must point to the exact generated artifact path.");
if (!String(screenshot.spec || "").includes("1280x800")) throw new Error("Store screenshot contract must retain the exact 1280x800 dimension requirement.");

const icon = contract.requiredStoreAssets?.find((asset) => asset.id === "icon_128_png");
if (!icon || icon.status !== "ready" || icon.path !== "src/assets/icons/browsercrew-128.png" || icon.sha256 !== "7d707768a259207a1a5963c8cf351f297ccef482153f50d14fd05abf0682ce09") {
  throw new Error("The reviewed 128x128 icon must be marked ready at its exact packaged path and digest.");
}
if (!String(icon.spec || "").includes("96x96") || !String(icon.spec || "").includes("16px transparent padding")) {
  throw new Error("The reviewed 128x128 icon contract must preserve Chrome Web Store visible-artwork padding requirements.");
}
const promo = contract.requiredStoreAssets?.find((asset) => asset.id === "small_promo_440x280");
if (!promo || promo.status !== "generated_by_ci" || promo.path !== "artifacts/store-media/browsercrew-small-promo-440x280.png") {
  throw new Error("The 440x280 promotional tile must be generated by exact-candidate CI at its reviewed artifact path.");
}

const manifest = JSON.parse(await readFile("manifest.json", "utf8"));
const expectedIcons = {
  "16": "src/assets/icons/browsercrew-16.png",
  "32": "src/assets/icons/browsercrew-32.png",
  "48": "src/assets/icons/browsercrew-48.png",
  "128": "src/assets/icons/browsercrew-128.png"
};
if (JSON.stringify(manifest.icons) !== JSON.stringify(expectedIcons)) throw new Error("Manifest icon mapping must exactly match the reviewed BrowserCrew icon set.");
if (JSON.stringify(manifest.action?.default_icon) !== JSON.stringify(expectedIcons)) throw new Error("Toolbar icon mapping must exactly match the reviewed BrowserCrew icon set.");

const workflow = await readFile(".github/workflows/quality.yml", "utf8");
for (const phrase of [
  "npm run store-media-smoke",
  "name: store-media-evidence",
  "path: artifacts/store-media",
  "if-no-files-found: error"
]) if (!workflow.includes(phrase)) throw new Error(`Quality workflow store-media gate missing: ${phrase}`);

const pkg = JSON.parse(await readFile("package.json", "utf8"));
if (pkg.scripts?.["store-media-check"] !== "node scripts/store-media-check.mjs") throw new Error("store-media-check must stay wired in package.json.");
if (pkg.scripts?.["store-media-smoke"] !== "node scripts/store-media-smoke.mjs && node scripts/store-assets-smoke.mjs") throw new Error("store-media-smoke must generate screenshot evidence and then verify/copy the reviewed icon and render the promo asset.");
if (!String(pkg.scripts?.check || "").includes("store-media-check.mjs")) throw new Error("npm run check must enforce Chrome Web Store media contracts.");

const storeDoc = await readFile("docs/CHROME-WEB-STORE-v0.2.md", "utf8");
for (const phrase of [
  "1280×800 Workspace screenshot — **generated by exact-candidate CI**",
  "128×128 PNG extension/store icon — **ready and packaged**",
  "440×280 small promotional tile — **generated by exact-candidate CI**"
]) if (!storeDoc.includes(phrase)) throw new Error(`Chrome Web Store submission pack media state missing: ${phrase}`);

const mediaDoc = await readFile("docs/STORE-MEDIA-v0.2.md", "utf8");
for (const phrase of [
  "Engineering media readiness only — not submitted and not approved.",
  "artifacts/store-media/browsercrew-workspace-1280x800.png",
  "src/assets/icons/browsercrew-128.png",
  "artifacts/store-media/browsercrew-small-promo-440x280.png",
  "exact candidate SHA",
  "reviewed SHA-256",
  "Issue #50 remains the tracking blocker"
]) if (!mediaDoc.includes(phrase)) throw new Error(`Dedicated store-media evidence doc missing: ${phrase}`);

const evidence = await readFile("docs/RELEASE-EVIDENCE-v0.2.md", "utf8");
if (!evidence.includes("V02-B08")) throw new Error("Release ledger must retain V02-B08.");
if (evidence.includes("`V02-B08` — **Resolved")) throw new Error("Generated media evidence cannot resolve external Chrome Web Store review.");

console.log("BrowserCrew V02-B08 store-media contracts passed (screenshot/icon/promo ready; external store review still blocked).\n");
