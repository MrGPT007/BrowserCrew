import { access, readFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
for (const file of [
  "scripts/store-media-smoke.mjs",
  "store/chrome-web-store-v0.2.json",
  ".github/workflows/quality.yml",
  "package.json",
  "docs/CHROME-WEB-STORE-v0.2.md",
  "docs/STORE-MEDIA-v0.2.md",
  "docs/RELEASE-EVIDENCE-v0.2.md"
]) await access(file);

await execFileAsync(process.execPath, ["--check", "scripts/store-media-smoke.mjs"]);

const smoke = await readFile("scripts/store-media-smoke.mjs", "utf8");
for (const phrase of [
  'channel: "chromium",',
  'viewport: { width: 1280, height: 800 }',
  'browsercrew-workspace-1280x800.png',
  'await panel.screenshot({ path: screenshotPath, type: "png", fullPage: false })',
  'assert.deepEqual(dimensions, { width: 1280, height: 800 }',
  'kind: "browsercrew.store_media_evidence"',
  'event?.pull_request?.head?.sha || event?.after',
  'Installed extension connected through the real Connect AI surface',
  'real Workspace compare UI with three user-selected pages'
]) if (!smoke.includes(phrase)) throw new Error(`Store media smoke contract missing: ${phrase}`);

const contract = JSON.parse(await readFile("store/chrome-web-store-v0.2.json", "utf8"));
const screenshot = contract.requiredStoreAssets?.find((asset) => asset.id === "screenshot_1280x800");
if (!screenshot) throw new Error("Store contract must track the required 1280x800 screenshot.");
if (screenshot.status !== "generated_by_ci") throw new Error("The required store screenshot must be marked generated_by_ci after executable capture proof is added.");
if (screenshot.path !== "artifacts/store-media/browsercrew-workspace-1280x800.png") throw new Error("Store screenshot contract must point to the exact generated artifact path.");
if (!String(screenshot.spec || "").includes("1280x800")) throw new Error("Store screenshot contract must retain the exact 1280x800 dimension requirement.");
for (const id of ["icon_128_png", "small_promo_440x280"]) {
  const asset = contract.requiredStoreAssets?.find((item) => item.id === id);
  if (!asset || asset.status !== "missing") throw new Error(`${id} must remain truthfully missing until a real asset is supplied.`);
}

const workflow = await readFile(".github/workflows/quality.yml", "utf8");
for (const phrase of [
  "npm run store-media-smoke",
  "name: store-media-evidence",
  "path: artifacts/store-media",
  "if-no-files-found: error"
]) if (!workflow.includes(phrase)) throw new Error(`Quality workflow store-media gate missing: ${phrase}`);

const pkg = JSON.parse(await readFile("package.json", "utf8"));
if (pkg.scripts?.["store-media-check"] !== "node scripts/store-media-check.mjs") throw new Error("store-media-check must stay wired in package.json.");
if (pkg.scripts?.["store-media-smoke"] !== "node scripts/store-media-smoke.mjs") throw new Error("store-media-smoke must stay wired in package.json.");
if (!String(pkg.scripts?.check || "").includes("store-media-check.mjs")) throw new Error("npm run check must enforce Chrome Web Store media contracts.");

const storeDoc = await readFile("docs/CHROME-WEB-STORE-v0.2.md", "utf8");
for (const phrase of [
  "1280×800 Workspace screenshot — **generated by exact-candidate CI**",
  "128×128 PNG extension/store icon in the extension ZIP — **required, missing**",
  "440×280 small promotional tile — **required, missing**"
]) if (!storeDoc.includes(phrase)) throw new Error(`Chrome Web Store submission pack media state missing: ${phrase}`);

const mediaDoc = await readFile("docs/STORE-MEDIA-v0.2.md", "utf8");
for (const phrase of [
  "Engineering media readiness only — not submitted and not approved.",
  "artifacts/store-media/browsercrew-workspace-1280x800.png",
  "installed Manifest V3 extension",
  "exact candidate SHA",
  "128×128 PNG extension/store icon",
  "440×280 small promotional tile",
  "Issue #50 remains the tracking blocker"
]) if (!mediaDoc.includes(phrase)) throw new Error(`Dedicated store-media evidence doc missing: ${phrase}`);

const evidence = await readFile("docs/RELEASE-EVIDENCE-v0.2.md", "utf8");
if (!evidence.includes("V02-B08")) throw new Error("Release ledger must retain V02-B08.");
if (evidence.includes("`V02-B08` — **Resolved")) throw new Error("Generated media evidence cannot resolve external Chrome Web Store review.");

console.log("BrowserCrew V02-B08 store-media contracts passed (screenshot generated in CI; external store review still blocked).\n");
